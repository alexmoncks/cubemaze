; music.asm - Cube Maze 3D sound driver for the MSX2 cartridge (GNU z80asm 1.8)
;
; BGM: the original game's two looping PLAY scores (channel 0 arpeggio, channel 1 bass),
;      on the OPLL (MSX-MUSIC / FM-PAC) when one is found, else on PSG A and B.
; SFX: the four original effects, always on PSG C.
; Time: 1 beat = 600 units; each snd_tick (60 Hz) removes MUS_STEP = 16 units (T96).
;       A voice's next event is due when its remaining time is <= 0; a note adds its
;       length to what is left (Playload's carry), so the music never drifts.
;
; Interface (the includer defines MUS_RAM: equ <address>; 128 bytes reserved, 40 used):
;   snd_init   once at start-up, interrupts disabled. Detects MSX-MUSIC (RDSLT over all
;              slots/subslots), sets up the PSG (and the OPLL), starts the BGM.
;              Changes AF, BC, DE, HL. Interrupts stay disabled.
;   snd_tick   once per vertical blank. Changes AF, BC, DE, HL (IX, IY, AF'..HL' kept).
;   sfx_play   A = 0..3: starts that SFX on PSG C (restarts it). Changes AF, DE, HL.
;   MUS_FLAG   (RAM byte) 0 = PSG only, 1 = OPLL found.
; Assemble with the music directory on the include path (z80asm -I <dir>) for
; music_data.asm (generated by music.py).
;
; Stream (music_data.asm): a header byte (volume at the start), then: note = 2 * pitch
; index (00h..DEh), length word; rest = 0F0h, length word; 0E0h+n = volume n;
; 0FDh = idle; 0FEh, address = loop; 0FFh = end.

MUS_RDSLT:  equ 000Ch           ; BIOS: A = slot, HL = address -> A
MUS_WRSLT:  equ 0014h           ; BIOS: writes E to slot A, address HL
MUS_EXPTBL: equ 0FCC1h          ; bit 7 set: primary slot n is expanded

MUS_FLAG:   equ MUS_RAM+0       ; 0 = PSG, 1 = OPLL present
MUS_PAC:    equ MUS_RAM+1       ; slot of an FM-PAC (0FFh = none)
MUS_PRIM:   equ MUS_RAM+2       ; primary slot being scanned
MUS_CUR:    equ MUS_RAM+3       ; slot ID being scanned
MUS_BUF:    equ MUS_RAM+8       ; (8) ID read from 401Ch
MUS_V0:     equ MUS_RAM+16      ; voice 0: BGM channel 0
MUS_V1:     equ MUS_RAM+24      ; voice 1: BGM channel 1
MUS_V2:     equ MUS_RAM+32      ; voice 2: SFX
MUS_END:    equ MUS_RAM+40
; voice: +0 remaining-1 (signed word; < 0: next event due), +2 stream pointer,
;        +4 volume (AY level), +5 copy of OPLL reg 20h+ch
MUS_BUFOFS: equ (MUS_BUF-401Ch) & 0FFFFh

; ------------------------------------------------------------------ snd_tick
snd_tick:
        ld hl,(MUS_V0)
        bit 7,h
        call nz,mus_ev0
        ld de,0-MUS_STEP
        add hl,de
        ld (MUS_V0),hl
        ld hl,(MUS_V1)
        bit 7,h
        call nz,mus_ev1
        ld de,0-MUS_STEP
        add hl,de
        ld (MUS_V1),hl
        ld hl,(MUS_V2)
        bit 7,h
        call nz,mus_ev2
        ld de,0-MUS_STEP
        add hl,de
        ld (MUS_V2),hl
        ret

; Each mus_evN: the next event of voice N is due. Returns HL = remaining-1 + the
; length of the note started. Control bytes go through mus_ctl (rare).
; ---- voice 0: BGM channel 0 (PSG A or OPLL channel 0)
mus_ev0:
        ld de,(MUS_V0+2)
        ld a,(de)
        cp 0E0h
        jr c,mus_e0n
        ld c,0
        ld hl,MUS_V0
        call mus_ctl
mus_e0n:
        inc de
        ld b,a
        ld a,(MUS_FLAG)
        or a
        jr nz,mus_f0
        ld a,b
        add a,mus_per & 0FFh
        ld l,a
        adc a,mus_per >> 8
        sub l
        ld h,a
        xor a
        out (0A0h),a            ; R0, R1: period
        ld a,(hl)
        out (0A1h),a
        inc hl
        ld a,1
        out (0A0h),a
        ld a,(hl)
        out (0A1h),a
        ld a,8
        out (0A0h),a            ; R8: volume
        ld a,(MUS_V0+4)
        out (0A1h),a
        ex de,hl
        ld c,(hl)
        inc hl
        ld b,(hl)
        inc hl
        ld (MUS_V0+2),hl
        ld hl,(MUS_V0)
        add hl,bc
        ret
mus_f0:                         ; OPLL channel 0: key off, F-number, key on
        ld a,20h
        out (7Ch),a
        ld a,(MUS_V0+5)
        and 0EFh
        out (7Dh),a             ; key off (at the old pitch)
        ld a,b
        add a,mus_fnum & 0FFh
        ld l,a
        adc a,mus_fnum >> 8
        sub l
        ld h,a
        ld b,(hl)
        inc hl
        ld a,(hl)
        or 10h
        ld (MUS_V0+5),a
        ex de,hl
        ld e,(hl)
        inc hl
        ld d,(hl)
        inc hl
        ld (MUS_V0+2),hl        ; (>= 84 T-states since the data write)
        ld a,10h
        out (7Ch),a
        ld a,b
        out (7Dh),a             ; F-number low
        ld hl,(MUS_V0)
        add hl,de
        ex (sp),hl              ; delay: >= 84 T-states before the next address
        ex (sp),hl
        nop
        ld a,20h
        out (7Ch),a
        ld a,(MUS_V0+5)
        out (7Dh),a             ; block, F-number bit 8, key on
        ret

; ---- voice 1: BGM channel 1 (PSG B or OPLL channel 1)
mus_ev1:
        ld de,(MUS_V1+2)
        ld a,(de)
        cp 0E0h
        jr c,mus_e1n
        ld c,1
        ld hl,MUS_V1
        call mus_ctl
mus_e1n:
        inc de
        ld b,a
        ld a,(MUS_FLAG)
        or a
        jr nz,mus_f1
        ld a,b
        add a,mus_per & 0FFh
        ld l,a
        adc a,mus_per >> 8
        sub l
        ld h,a
        ld a,2
        out (0A0h),a            ; R2, R3: period
        ld a,(hl)
        out (0A1h),a
        inc hl
        ld a,3
        out (0A0h),a
        ld a,(hl)
        out (0A1h),a
        ld a,9
        out (0A0h),a            ; R9: volume
        ld a,(MUS_V1+4)
        out (0A1h),a
        ex de,hl
        ld c,(hl)
        inc hl
        ld b,(hl)
        inc hl
        ld (MUS_V1+2),hl
        ld hl,(MUS_V1)
        add hl,bc
        ret
mus_f1:                         ; OPLL channel 1
        ld a,21h
        out (7Ch),a
        ld a,(MUS_V1+5)
        and 0EFh
        out (7Dh),a
        ld a,b
        add a,mus_fnum & 0FFh
        ld l,a
        adc a,mus_fnum >> 8
        sub l
        ld h,a
        ld b,(hl)
        inc hl
        ld a,(hl)
        or 10h
        ld (MUS_V1+5),a
        ex de,hl
        ld e,(hl)
        inc hl
        ld d,(hl)
        inc hl
        ld (MUS_V1+2),hl
        ld a,11h
        out (7Ch),a
        ld a,b
        out (7Dh),a
        ld hl,(MUS_V1)
        add hl,de
        ex (sp),hl
        ex (sp),hl
        nop
        ld a,21h
        out (7Ch),a
        ld a,(MUS_V1+5)
        out (7Dh),a
        ret

; ---- voice 2: SFX (PSG C)
mus_ev2:
        ld de,(MUS_V2+2)
        ld a,(de)
        cp 0E0h
        jr c,mus_e2n
        ld c,2
        ld hl,MUS_V2
        call mus_ctl
mus_e2n:
        inc de
        add a,mus_per & 0FFh
        ld l,a
        adc a,mus_per >> 8
        sub l
        ld h,a
        ld a,4
        out (0A0h),a            ; R4, R5: period
        ld a,(hl)
        out (0A1h),a
        inc hl
        ld a,5
        out (0A0h),a
        ld a,(hl)
        out (0A1h),a
        ld a,10
        out (0A0h),a            ; R10: volume
        ld a,(MUS_V2+4)
        out (0A1h),a
        ex de,hl
        ld c,(hl)
        inc hl
        ld b,(hl)
        inc hl
        ld (MUS_V2+2),hl
        ld hl,(MUS_V2)
        add hl,bc
        ret

; ------------------------------------------------------------------ control bytes
; HL = voice, C = channel, DE -> a control byte. Returns A = the next note byte with
; DE -> it; for a rest, the end or idle it returns straight to snd_tick (drops the
; return into mus_evN) with HL = the voice's remaining-1 (+ the rest's length).
mus_ctl:
        ld a,(de)
        cp 0E0h
        ret c                   ; a note
        inc de
        cp 0F0h
        jr c,mus_cvol
        jr z,mus_crest
        cp 0FEh
        jr z,mus_cloop
        jr c,mus_cidle          ; 0FDh: idle
        call mus_mute           ; 0FFh: end -> silence, idle
        push hl
        inc hl
        inc hl
        ld (hl),mus_idleb & 0FFh
        inc hl
        ld (hl),mus_idleb >> 8
        pop hl
mus_cidle:
        pop af
        ld hl,7FFFh
        ret
mus_cloop:
        ex de,hl
        ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a
        ex de,hl                ; DE = loop address
        jr mus_ctl
mus_crest:
        call mus_mute
        ex de,hl
        ld c,(hl)
        inc hl
        ld b,(hl)
        inc hl
        ex de,hl                ; BC = length, DE = pointer, HL = voice
        push hl
        inc hl
        inc hl
        ld (hl),e
        inc hl
        ld (hl),d
        pop hl
        ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a
        add hl,bc
        pop af
        ret
mus_cvol:                       ; volume: voice+4; on an OPLL channel, reg 30h+ch
        and 0Fh
        push de
        push hl
        ld de,4
        add hl,de
        cp (hl)
        ld (hl),a
        jr z,mus_cv9
        ld b,a
        ld a,c
        cp 2
        ld a,b
        call nz,mus_fmatt
mus_cv9:
        pop hl
        pop de
        jr mus_ctl

; silence channel C of voice HL: PSG volume 0 / OPLL key off. Keeps C, DE, HL.
mus_mute:
        ld a,c
        cp 2
        jr z,mus_mpsg
        ld a,(MUS_FLAG)
        or a
        jr z,mus_mpsg
        push hl
        push de
        ld de,5
        add hl,de
        ld a,(hl)
        and 0EFh
        ld (hl),a
        ld e,a
        ld a,c
        add a,20h
        call mus_opll
        pop de
        pop hl
        ret
mus_mpsg:
        ld a,c
        add a,8
        out (0A0h),a
        xor a
        out (0A1h),a
        ret

; OPLL write: A = register, E = data; changes A only. YM2413 timing: 15 T-states
; from the address write to the data write (>= 12); the delay here plus the shortest
; way to the next address write (ret 10 + call 17 + out 11) is >= 84 T-states.
mus_opll:
        out (7Ch),a
        ld a,e
        out (7Dh),a
        ex (sp),hl
        ex (sp),hl
        nop
        nop
        ret

; ------------------------------------------------------------------ sfx_play
sfx_play:
        and 3
        add a,a
        ld e,a
        ld d,0
        ld hl,mus_sfxtab
        add hl,de
        ld e,(hl)
        inc hl
        ld d,(hl)
        ld hl,MUS_V2
; HL = voice, DE = stream: remaining 0 (due at the next tick), volume = the
; header byte, pointer = DE+1. Returns A = volume.
mus_setv:
        ld (hl),0FFh
        inc hl
        ld (hl),0FFh
        inc hl
        ld a,(de)
        inc de
        ld (hl),e
        inc hl
        ld (hl),d
        inc hl
        ld (hl),a
        ret

; ------------------------------------------------------------------ snd_init
snd_init:
        ld hl,MUS_RAM
        ld b,MUS_END-MUS_RAM
mus_clr:
        ld (hl),0
        inc hl
        djnz mus_clr
        ld a,0FFh
        ld (MUS_PAC),a
        xor a
mus_scanp:                      ; every primary slot ...
        ld (MUS_PRIM),a
        ld e,a
        ld d,0
        ld hl,MUS_EXPTBL
        add hl,de
        ld a,(hl)
        and 80h
        or e
mus_scans:                      ; ... and every subslot of an expanded one
        ld (MUS_CUR),a
        call mus_check
        ld a,(MUS_FLAG)
        or a
        jr nz,mus_found         ; internal MSX-MUSIC: done
        ld a,(MUS_CUR)
        or a
        jp p,mus_nexts
        add a,4
        bit 4,a
        jr z,mus_scans
mus_nexts:
        ld a,(MUS_PRIM)
        inc a
        cp 4
        jr c,mus_scanp
        ld a,(MUS_PAC)          ; no internal one: an FM-PAC?
        inc a
        jr z,mus_found
        ld hl,7FF6h             ; enable its I/O ports: 7FF6h bit 0
        ld a,(MUS_PAC)
        call MUS_RDSLT
        di
        or 1
        ld e,a
        ld hl,7FF6h
        ld a,(MUS_PAC)
        call MUS_WRSLT
        di
        ld a,1
        ld (MUS_FLAG),a
mus_found:
        ld a,7                  ; PSG R7: tones on, noise off, port B out / port A in
        out (0A0h),a
        ld a,0B8h
        out (0A1h),a
        ld c,8                  ; R8-R10: volume 0
mus_psgi:
        ld a,c
        out (0A0h),a
        xor a
        out (0A1h),a
        inc c
        ld a,c
        cp 11
        jr nz,mus_psgi
        ld a,(MUS_FLAG)
        or a
        jr z,mus_go
        ld a,0Eh                ; OPLL: rhythm off,
        ld e,0
        call mus_opll
        ld c,20h                ; all keys off,
mus_oi1:
        ld a,c
        ld e,0
        call mus_opll
        inc c
        ld a,c
        cp 29h
        jr nz,mus_oi1
        ld c,30h                ; every channel at minimum volume,
mus_oi2:
        ld a,c
        ld e,0Fh
        call mus_opll
        inc c
        ld a,c
        cp 39h
        jr nz,mus_oi2
mus_go:
        ld hl,MUS_V0            ; start the BGM
        ld de,mus_bgm0
        call mus_setv
        ld c,0
        call mus_fmatt
        ld hl,MUS_V1
        ld de,mus_bgm1
        call mus_setv
        ld c,1
        call mus_fmatt
        ld hl,mus_idleb         ; SFX voice idle
        ld (MUS_V2+2),hl
        ld hl,7FFFh
        ld (MUS_V2),hl
        ret

; A = volume of OPLL channel C (if MSX-MUSIC): reg 30h+C = instrument | attenuation
mus_fmatt:
        ld b,a
        ld a,(MUS_FLAG)
        or a
        ret z
        ld hl,mus_att
        ld e,b
        ld d,0
        add hl,de
        ld b,(hl)
        ld hl,mus_inst
        ld e,c
        add hl,de
        ld a,(hl)
        or b
        ld e,a
        ld a,c
        add a,30h
        jp mus_opll

; reads the 8 bytes at 401Ch of slot (MUS_CUR): "APRLOPLL" -> MUS_FLAG = 1,
; "PAC2OPLL" -> MUS_PAC = slot (the first one found)
mus_check:
        ld hl,401Ch
mus_rd:
        push hl
        ld a,(MUS_CUR)
        call MUS_RDSLT
        di
        pop hl
        push hl
        ld de,MUS_BUFOFS
        add hl,de
        ld (hl),a
        pop hl
        inc l
        ld a,l
        cp 24h
        jr nz,mus_rd
        ld de,mus_id1
        call mus_cmp8
        jr nz,mus_chk2
        ld a,1
        ld (MUS_FLAG),a
        ret
mus_chk2:
        ld de,mus_id2
        call mus_cmp8
        ret nz
        ld a,(MUS_PAC)
        inc a
        ret nz
        ld a,(MUS_CUR)
        ld (MUS_PAC),a
        ret
mus_cmp8:
        ld hl,MUS_BUF
        ld b,8
mus_cmpl:
        ld a,(de)
        cp (hl)
        ret nz
        inc hl
        inc de
        djnz mus_cmpl
        ret

mus_id1:   db "APRLOPLL"
mus_id2:   db "PAC2OPLL"
mus_inst:  db MUS_FM_INST0, MUS_FM_INST1
mus_idleb: db 0FDh

        include "music_data.asm"
