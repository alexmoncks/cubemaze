"""The tables of cubemaze.asm, from ztables.py / zmodel.py (the same numbers
the model uses):

  out/inc/equ.asm      constants and the addresses of the banked tables
  out/inc/tab0.asm     the tables of bank 0 (always visible, 4000h-7FFFh)
  out/bank1.bin        8000h: title spin, roll matrices
  out/bank2.bin        8000h: clear spin, per size: neighbours
  out/bank3.bin        8000h: texture rectangles per size, font masks
  out/bank4.bin        8000h: ball images, background checkerboard and stars
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import ztables as zt  # noqa: E402
import zmodel as zm  # noqa: E402

OUT = os.path.join(HERE, "out")
INC = os.path.join(OUT, "inc")


def w16(v):
    v &= 0xFFFF
    return bytes([v & 0xFF, v >> 8])


class Bank:
    def __init__(self, n):
        self.n, self.data, self.labels = n, bytearray(), {}

    def put(self, name, b):
        self.labels[name] = 0x8000 + len(self.data)
        self.data += bytes(b)

    def finish(self):
        assert len(self.data) <= 0x4000, (self.n, len(self.data))
        return bytes(self.data) + bytes(0x4000 - len(self.data))


def mats(lst):
    return b"".join(w16(v) for m in lst for v in m)


def main():
    os.makedirs(INC, exist_ok=True)
    equ = {}
    b1, b2, b3, b4 = Bank(1), Bank(2), Bank(3), Bank(4)
    # bank 1
    b1.put("T_TITLE", mats(zt.TITLE))
    b1.put("T_ROLLB", mats([m for a in range(4) for m in zt.ROLLB[a]]))
    b1.put("T_ROLLR", mats([m for a in range(4) for m in zt.ROLLR[a]]))
    # bank 2
    b2.put("T_CLEAR", mats(zt.CLEARM))
    for lv in zt.LEVELS:
        L = zt.LV[lv]
        mv = bytearray()
        for row in L.MV:
            for ci, din in row:
                mv += bytes([ci, din])
        b2.put(f"T_MV{lv}", mv)
        # texture rectangles: kinds C43 P10 P36 WW WL GB, t = -lv..lv -> x0, x1
        halves = [L.HC43, L.HP10, L.HP36, L.WW, L.WL, L.GB]
        tx, ty = bytearray(), bytearray()
        for h in halves:
            for t in range(-lv, lv + 1):
                tx += bytes([L.tx(t * L.HG - h), L.tx(t * L.HG + h)])
                ty += bytes([L.ty(t * L.HG - h), L.ty(t * L.HG + h)])
        b3.put(f"T_TX{lv}", tx)
        b3.put(f"T_TY{lv}", ty)
    # bank 3: font masks (42 rows x 256 bytes), ball images
    b3.put("T_FONT", zm.rows_bytes(zm.font_rows()))
    bi = bytearray()
    for pr in range(zt.PR_MIN, zt.PR_MAX + 1):
        for x, y, wd, ht, cx, cy, rows in zm.BALLS[pr]:
            for k, row in enumerate(rows):
                ad = (y + k) * 256 + (x >> 1)
                bi += bytes([ad & 0xFF, ((ad >> 8) & 0x3F) | 0x40, ad >> 14, len(row) // 2])
                bi += zm.rows_bytes([row])
    bi += bytes([0xFF, 0xFF, 0xFF, 0xFF])
    b4.put("T_BALLIMG", bi)
    # background: the checkerboard rows (2 patterns) + the star bytes
    bg = zm.background_rows()
    chk = zm.rows_bytes(((zm.np.mgrid[0:212, 0:512][1] // zt.CHECK_W + zm.np.mgrid[0:212, 0:512][0] // zt.CHECK_H) & 1).astype(zm.np.uint8))
    full = zm.rows_bytes(bg)
    stars = bytearray()
    nst = 0
    for i in range(len(full)):
        if full[i] != chk[i]:
            a = zt.BG_Y * 256 + i
            stars += bytes([a & 0xFF, (a >> 8) & 0x3F | 0x40, a >> 14, full[i]])
            nst += 1
    stars += bytes([0xFF] * 4)
    b4.put("T_STARS", stars)
    # the two checkerboard rows (even, odd line), 256 bytes each
    b4.put("T_CHECK", chk[0:256] + chk[256:512])
    assert all(chk[y * 256:(y + 1) * 256] == chk[(y & 1) * 256:((y & 1) + 1) * 256] for y in range(212))

    for b in (b1, b2, b3, b4):
        for k, v in b.labels.items():
            equ[k] = v
    equ.update(dict(
        TBANK1=1, TBANK2=2, TBANK3=3, TBANK4=4,
        TZ=zt.TZ, G_FOCAL=zt.FOCAL, G_CX=zt.CX, G_CY=zt.CY, G_ZNEAR=zt.ZNEAR, G_W=zt.W, G_H=zt.H,
        VSLOT=zt.VSLOT, FSLOT=zt.FSLOT, V_SCRATCH=zt.V_SCRATCH, F_SCRATCH=zt.F_SCRATCH,
        N_SCRATCH=zt.N_SCRATCH, K_END=zt.K_END, J_END=zt.J_END, SPIN_N=zt.SPIN_N, GOAL_N=zt.GOAL_N,
        VIS_T=zt.VIS_T, BG_Y=zt.BG_Y, FONT_Y=zt.FONT_Y, TEX_Y=zt.TEX_Y, BALL_Y=zt.BALL_Y,
        SHADOW_Y=zt.SHADOW_Y, PR_MIN=zt.PR_MIN, ADV=zt.ADV, SHADOW_K=zt.SHADOW_K,
        DITH_GREY=zt.D_GREY, DITH_ACT=zt.D_ACT, NSTARS=nst,
        C0=zt.C[0], C1=zt.C[1], C2=zt.C[2], C3=zt.C[3], C4=zt.C[4], C5=zt.C[5], C6=zt.C[6], C7=zt.C[7],
        NCODE_ABC=len(zt.CODE_ABC), HX0=zt.hx(0), HX160=zt.hx(160)))
    with open(os.path.join(INC, "equ.asm"), "w") as f:
        f.write("; generated by gen_assets.py\n")
        for k, v in equ.items():
            f.write(f"{k}: equ {v}\n")

    # ---------------------------------------------------------------- bank 0 tables
    t = []

    def db(name, vals, per=16):
        t.append(f"{name}:")
        vals = list(vals)
        for i in range(0, len(vals), per):
            t.append("        db " + ", ".join(str(v & 0xFF) for v in vals[i:i + per]))
        if not vals:
            t.append("        ; (empty)")

    def dw(name, vals, per=8):
        t.append(f"{name}:")
        vals = list(vals)
        for i in range(0, len(vals), per):
            t.append("        dw " + ", ".join(str(v & 0xFFFF) for v in vals[i:i + per]))

    # PERM[o]: for each column j: k * 2 (byte offset in a row), sign (0 / 1 negate)
    db("T_PERM", [x for o in range(24) for k, s in zt.PERM[o] for x in (2 * k, 1 if s < 0 else 0)])
    # PERM9[o]: element e = 3 i + j of B . P(o) comes from element 3 i + k_j (2 * that, negate)
    db("T_PERM9", [x for o in range(24) for i in range(3) for j in range(3)
                   for x in (2 * (3 * i + zt.PERM[o][j][0]), 1 if zt.PERM[o][j][1] < 0 else 0)])
    db("T_ROLLNEXT", [x for o in range(24) for x in zt.ROLLNEXT[o]])
    # roll axis for (o, new face): 0..3, FFh if not horizontal
    wn2a = {0: 0, 1: 1, 4: 2, 5: 3}
    db("T_ROLLAX", [wn2a.get(zt.ROTN[o][f], 0xFF) for o in range(24) for f in range(6)])
    db("T_DIRMAP", [x for o in range(24) for x in zt.DIRMAP[o]])
    # FACE_AXES[f]: (component * 2, negate) for n, u, v
    db("T_FAXES", [x for f in range(6) for i, s in zt.FACE_AXES[f] for x in (2 * i, 1 if s < 0 else 0)])
    db("T_FCOL", zt.FACE_COLOUR)
    dw("T_K10", zt.K10)
    dw("T_GOALH1", zt.GOAL_H1)
    dw("T_GOALH2", zt.GOAL_H2)
    # per size: a block of words (see LV_* offsets)
    lvw = []
    for lv in zt.LEVELS:
        L = zt.LV[lv]
        rmax_g = min((zt.VSLOT - L.nv_floor - 8) // 8, (zt.FSLOT - lv * lv - 2) // 2)
        rmax_n = min((zt.VSLOT - L.nv_floor) // 8, (zt.FSLOT - lv * lv) // 2)
        words = [L.HG, L.KS, L.WL, L.WW, L.HMID, L.HTOP, L.GB, L.HBALL] + L.PR_Z + \
            [L.cw, L.ch, L.nv_floor, rmax_g, rmax_n, equ[f"T_MV{lv}"], equ[f"T_TX{lv}"], equ[f"T_TY{lv}"],
             lv * lv, 6 * lv * lv]
        lvw.append(words)
    assert len(set(len(w) for w in lvw)) == 1
    t.append(f"LV_SIZE: equ {2 * len(lvw[0])}")
    names = ["HG", "KS", "WL", "WW", "HMID", "HTOP", "GB", "HBALL"] + [f"PRZ{p}" for p in range(4, 11)] + \
        ["CW", "CH", "NVF", "RMAXG", "RMAXN", "PMV", "PTX", "PTY", "NN", "NCELL"]
    for i, n in enumerate(names):
        t.append(f"LV_{n}: equ {2 * i}")
    dw("T_LV", [x for w in lvw for x in w])
    # ball images: per pr: ball (sx, sy, w, h, cx, cy), shadow (same), words
    dw("T_BALLS", [v for pr in range(zt.PR_MIN, zt.PR_MAX + 1) for img in zm.BALLS[pr] for v in img[:6]])
    # palettes
    db("T_PAL0", zt.pal_bytes(zt.FACE_COLOUR[0]))
    db("T_PALACT", [x for c in range(8) for x in zt.pal_bytes(c, zt.D_ACT, 1)])
    # HUD: hx (words) and hy (bytes) tables
    dw("T_HX", [zt.hx(x) for x in range(0, 168)])
    db("T_HY", [zt.hy(y) for y in range(0, 148)])
    # glyph cells: ASCII 32..127 -> index in CHARSET (FFh: none)
    db("T_GLYPH", [zm.CHARSET.index(chr(c)) if chr(c) in zm.CHARSET else 0 for c in range(32, 128)])
    # glyph index -> (gx lo, gx hi, gy lo, gy hi)
    db("T_GCELL", [x for k in range(len(zm.CHARSET)) for x in
                   (zm.glyph_cell(zm.CHARSET[k])[0] & 0xFF, zm.glyph_cell(zm.CHARSET[k])[0] >> 8,
                    zm.glyph_cell(zm.CHARSET[k])[1] & 0xFF, zm.glyph_cell(zm.CHARSET[k])[1] >> 8)])
    # glyph cells by ASCII 32..127: gx (word), gy (word); unknown: the space
    cells = []
    for c in range(32, 128):
        ch = chr(c) if chr(c) in zm.CHARSET else " "
        gx, gy = zm.glyph_cell(ch)
        cells += [gx & 0xFF, gx >> 8, gy & 0xFF, gy >> 8]
    db("T_GCELL4", cells)
    # big digits 1..3: runs (r, c0, c1), FFh end
    for d in "123":
        db(f"T_BIG{d}", [x for run in zm.big_digit_runs(d) for x in run] + [0xFF])
    db("T_CODEABC", [ord(c) for c in zt.CODE_ABC])
    db("T_CODES", [ord(c) for u in (4, 5, 6) for c in zt.CODES[u]])
    with open(os.path.join(INC, "tab0.asm"), "w") as f:
        f.write("; generated by gen_assets.py\n" + "\n".join(t) + "\n")
    for b in (b1, b2, b3, b4):
        open(os.path.join(OUT, f"bank{b.n}.bin"), "wb").write(b.finish())
    print("banks:", [len(b.data) for b in (b1, b2, b3, b4)], "stars bytes", nst)


if __name__ == "__main__":
    main()
